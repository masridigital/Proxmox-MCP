# Kept equal to the "operate" tier in policy.py (test_operator_writes_match_operate_tier).
# Migrate, vzdump, wakeonlan and bulk actions are admin tier, so only rw reaches them here.

_PLACEHOLDER_RE = re.compile(r"^\{([a-z_]+)\}$")


def _compile(template: str) -> re.Pattern[str]:
    parts = []
    for seg in template.split("/")[1:]:
        m = _PLACEHOLDER_RE.match(seg)
        if m:
            parts.append(PLACEHOLDER_TYPES.get(m.group(1), _DEFAULT_PLACEHOLDER))
        else:
            parts.append(re.escape(seg))
    return re.compile("^/" + "/".join(parts) + "$") if parts else re.compile("^/$")


def _index(entries: Iterable[tuple[str, str]]) -> dict[str, list[re.Pattern[str]]]:
    table: dict[str, list[re.Pattern[str]]] = {m: [] for m in METHODS}
    for template, methods in entries:
        pattern = _compile(template)
        for method in methods.split():
            table[method].append(pattern)
    return table


_ALLOW = _index(ALLOWLIST)
_OPERATOR = _index(OPERATOR_WRITES)


def _blocked(reason: str) -> PermissionError:
    return PermissionError(f"blocked by outbound policy: {reason}")


def deny_reason(method: str, path: str) -> str | None:
    """The global deny rule a request hits, if any (path must already be valid)."""
    for methods, pattern, reason in _DENY:
        if method in methods and pattern.search(path):
            return reason
    return None


def check(method: str, path: str, mode: Mode) -> None:
    """Raise PermissionError("blocked by outbound policy: ...") unless allowed."""
    if method not in METHODS:
        raise _blocked("method not allowed")
    if mode not in MODES:
        raise _blocked("unknown mode")
    validate_path(path)
    reason = deny_reason(method, path)
    if reason:
        raise _blocked(reason)
    if method == "DELETE" and mode != "rw":
        raise _blocked("DELETE requires rw mode")
    if method != "GET":
        if mode == "ro":
            raise _blocked(f"{method} not allowed in read-only mode")
        if mode == "operator" and not any(p.match(path) for p in _OPERATOR[method]):
            raise _blocked(f"{method} {path} requires rw mode")
    if not any(p.match(path) for p in _ALLOW[method]):
        raise _blocked(f"{method} {path} is not in the allowlist")
